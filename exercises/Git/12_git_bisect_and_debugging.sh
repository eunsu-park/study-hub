# === Exercise 1: Manual Bisect ===
# Problem: Create a repository with 10 commits where a bug is
# introduced at commit 6, then use git bisect to find it.
exercise_1() {
    echo "=== Exercise 1: Manual Bisect ==="
    echo ""
    echo "Solution commands:"
    echo ""
    echo "  # Step 1: Create a repository with 10 commits (bug at commit 6)"
    echo "  git init bisect-lab && cd bisect-lab"
    echo "  for i in \$(seq 1 10); do"
    echo "    echo \"version \$i\" > app.py"
    echo "    if [ \$i -eq 6 ]; then"
    echo "      echo 'BUG INTRODUCED' >> app.py"
    echo "    fi"
    echo "    git add app.py"
    echo "    git commit -m \"Commit \$i\""
    echo "  done"
    echo ""
    echo "  # Step 2: Note the first commit hash"
    echo "  FIRST_COMMIT=\$(git rev-list --max-parents=0 HEAD)"
    echo ""
    echo "  # Step 3: Start bisecting"
    echo "  git bisect start"
    echo "  git bisect bad HEAD         # Current state has the bug"
    echo "  git bisect good \$FIRST_COMMIT  # First commit was clean"
    echo "  # Bisecting: 4 revisions left to test after this (roughly 3 steps)"
    echo ""
    echo "  # Step 4: At each checkout, test for the bug"
    echo "  grep -q 'BUG INTRODUCED' app.py && git bisect bad || git bisect good"
    echo "  # Repeat this command at each step"
    echo "  # Git narrows the range by half each time"
    echo ""
    echo "  # Step 5: After ~3-4 steps, Git reports:"
    echo "  # <hash> is the first bad commit"
    echo "  # commit <hash>"
    echo "  # Author: ..."
    echo "  #     Commit 6"
    echo ""
    echo "  # Step 6: Return to your original branch"
    echo "  git bisect reset"
    echo ""
    echo "Key takeaway:"
    echo "  Bisect uses binary search: 10 commits need ~3-4 steps instead of 10."
    echo "  For 1000 commits, you need only ~10 steps. Always reset when done."
}

