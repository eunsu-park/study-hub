    echo "  git branch -d feature/b"
    echo "  # Both deleted successfully"
    echo ""
    echo "  # Step 7: Attempting to delete unmerged branch with -d fails safely"
    echo "  git branch -d feature/c"
    echo "  # error: The branch 'feature/c' is not fully merged."
    echo "  # Use -D to force delete if you are sure"
    echo ""
    echo "Key takeaway:"
    echo "  git branch --merged lists branches safe to delete."
    echo "  git branch -d is safe (refuses unmerged). git branch -D force-deletes."
    echo "  Regularly clean up merged branches to keep the repo tidy."
}

