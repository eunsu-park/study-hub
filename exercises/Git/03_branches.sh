    echo "  git branch -d feature/user-authentication"
    echo ""
    echo "  # Step 2: Bugfix branch -- non-urgent bug"
    echo "  git switch -c bugfix/login-redirect"
    echo "  echo 'fixed redirect' > fix.py"
    echo "  git add . && git commit -m 'fix: correct login redirect URL'"
    echo "  git switch main && git merge bugfix/login-redirect"
    echo "  git branch -d bugfix/login-redirect"
    echo ""
    echo "  # Step 3: Hotfix branch -- urgent production fix"
    echo "  git switch -c hotfix/security-vulnerability"
    echo "  echo 'patched' > security.py"
    echo "  git add . && git commit -m 'fix: patch critical security vulnerability'"
    echo "  git switch main && git merge hotfix/security-vulnerability"
    echo "  git branch -d hotfix/security-vulnerability"
    echo ""
    echo "  # Step 4: Release branch -- preparing a release"
    echo "  git switch -c release/2.0.0"
    echo "  echo '# Team Project v2.0' > README.md"
    echo "  git add . && git commit -m 'chore: bump version to 2.0.0'"
    echo "  git switch main && git merge release/2.0.0"
    echo "  git branch -d release/2.0.0"
    echo ""
    echo "  # Step 5: View the clean history"
    echo "  git log --oneline"
    echo ""
    echo "Key takeaway:"
    echo "  Branch prefixes communicate intent at a glance:"
    echo "    feature/ = new functionality"
    echo "    bugfix/  = non-urgent bug fix"
    echo "    hotfix/  = urgent production fix"
    echo "    release/ = version release preparation"
