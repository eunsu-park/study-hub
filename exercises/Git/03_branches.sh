    echo ""
    echo "  # Step 4: Visualize again -- feature/c is still unmerged"
    echo "  git log --oneline --graph --all"
    echo ""
    echo "  # Step 5: List merged vs unmerged branches"
    echo "  git branch --merged"
    echo "  #   feature/a"
    echo "  #   feature/b"
    echo "  # * main"
