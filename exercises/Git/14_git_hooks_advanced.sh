# === Exercise 5: Server-Side Hook Simulation ===
# Problem: Simulate a pre-receive hook that enforces policies
# like no force push to main, no large files, and branch naming.
exercise_5() {
    echo "=== Exercise 5: Server-Side Hook Simulation ==="
    echo ""
    echo "Solution commands:"
    echo ""
    echo "  # Server-side hooks run on the Git server (GitHub, GitLab, self-hosted)."
    echo "  # We simulate one locally using a pre-push hook."
    echo ""
    echo "  # Step 1: Create a pre-push hook that simulates server policies"
    echo "  cat > .githooks/pre-push << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "# Simulate server-side pre-receive policies"
    echo ""
    echo "REMOTE=\$1"
    echo "URL=\$2"
    echo ""
    echo "while read local_ref local_sha remote_ref remote_sha; do"
    echo "    BRANCH=\$(echo \"\$remote_ref\" | sed 's|refs/heads/||')"
    echo ""
    echo "    # Policy 1: No force push to main or production"
    echo "    if echo \"\$BRANCH\" | grep -qE '^(main|production)\$'; then"
    echo "        if [ \"\$remote_sha\" != \"0000000000000000000000000000000000000000\" ]; then"
    echo "            MERGE_BASE=\$(git merge-base \"\$remote_sha\" \"\$local_sha\" 2>/dev/null)"
    echo "            if [ \"\$MERGE_BASE\" != \"\$remote_sha\" ]; then"
    echo "                echo \"ERROR: Force push to \$BRANCH is not allowed!\""
    echo "                exit 1"
    echo "            fi"
    echo "        fi"
    echo "    fi"
    echo ""
    echo "    # Policy 2: Branch naming convention"
    echo "    if ! echo \"\$BRANCH\" | grep -qE '^(main|develop|feature/.*|fix/.*|hotfix/.*|release/.*)\$'; then"
    echo "        echo \"ERROR: Branch '\$BRANCH' does not follow naming convention.\""
    echo "        echo \"Allowed: main, develop, feature/*, fix/*, hotfix/*, release/*\""
    echo "        exit 1"
    echo "    fi"
    echo ""
    echo "    # Policy 3: No large files (>5MB)"
    echo "    MAX_SIZE=5242880"
    echo "    if [ \"\$local_sha\" != \"0000000000000000000000000000000000000000\" ]; then"
    echo "        LARGE=\$(git rev-list --objects \"\$remote_sha..\$local_sha\" 2>/dev/null | \\"
    echo "            git cat-file --batch-check='%(objecttype) %(objectsize) %(rest)' | \\"
    echo "            grep ^blob | awk \"\\\$2 > \$MAX_SIZE {print \\\$3, \\\$2}\")"
    echo "        if [ -n \"\$LARGE\" ]; then"
    echo "            echo \"ERROR: Files exceeding 5MB detected:\""
    echo "            echo \"\$LARGE\""
    echo "            echo \"Use Git LFS for large files.\""
    echo "            exit 1"
    echo "        fi"
    echo "    fi"
    echo "done"
    echo ""
    echo "echo \"All push policies passed.\""
    echo "HOOKEOF"
    echo "  chmod +x .githooks/pre-push"
    echo ""
    echo "  # Step 2: Test branch naming policy"
    echo "  git switch -c my-random-branch"
    echo "  echo 'test' > test.txt && git add . && git commit -m 'test: policy check'"
    echo "  git push origin my-random-branch"
    echo "  # ERROR: Branch 'my-random-branch' does not follow naming convention."
    echo ""
    echo "  git switch -c feature/valid-name"
    echo "  git push origin feature/valid-name"
    echo "  # Passes -- name matches 'feature/*'"
    echo ""
    echo "Key takeaway:"
    echo "  Server-side hooks are the last line of defense. They cannot be"
    echo "  bypassed with --no-verify. On hosted platforms (GitHub, GitLab),"
    echo "  use branch protection rules and webhooks instead of custom hooks."
}

