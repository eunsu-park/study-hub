# === Exercise 3: Custom Hook Chain with Orchestrator ===
# Problem: Build a pre-commit hook system that runs multiple checks
# in a modular directory structure with proper error handling.
exercise_3() {
    echo "=== Exercise 3: Custom Hook Chain with Orchestrator ==="
    echo ""
    echo "Solution commands:"
    echo ""
    echo "  # Step 1: Create the hook directory structure"
    echo "  mkdir -p .githooks/pre-commit.d"
    echo ""
    echo "  # Step 2: Create the orchestrator script"
    echo "  cat > .githooks/pre-commit << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "HOOKS_DIR=\"\$(dirname \"\$0\")/pre-commit.d\""
    echo "EXIT_CODE=0"
    echo ""
    echo "for hook in \"\$HOOKS_DIR\"/*; do"
    echo "    if [ -x \"\$hook\" ]; then"
    echo "        echo \"Running \$(basename \"\$hook\")...\""
    echo "        \"\$hook\""
    echo "        if [ \$? -ne 0 ]; then"
    echo "            echo \"FAIL: \$(basename \"\$hook\")\""
    echo "            EXIT_CODE=1"
    echo "        else"
    echo "            echo \"PASS: \$(basename \"\$hook\")\""
    echo "        fi"
    echo "    fi"
    echo "done"
    echo ""
    echo "exit \$EXIT_CODE"
    echo "HOOKEOF"
    echo "  chmod +x .githooks/pre-commit"
    echo ""
    echo "  # Step 3: Create individual hook scripts"
    echo ""
    echo "  # 01 - Prevent direct commits to main"
    echo "  cat > .githooks/pre-commit.d/01-branch-check.sh << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "BRANCH=\$(git symbolic-ref --short HEAD)"
    echo "if [ \"\$BRANCH\" = \"main\" ] || [ \"\$BRANCH\" = \"production\" ]; then"
    echo "    echo \"Direct commits to \$BRANCH are not allowed. Use a PR.\""
    echo "    exit 1"
    echo "fi"
    echo "HOOKEOF"
    echo ""
    echo "  # 02 - Detect debug statements"
    echo "  cat > .githooks/pre-commit.d/02-no-debug.sh << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "if git diff --cached --diff-filter=ACM | grep -E '(console\\.log|debugger|import pdb|breakpoint\\(\\))' > /dev/null; then"
    echo "    echo \"Debug statements found in staged changes!\""
    echo "    exit 1"
    echo "fi"
    echo "HOOKEOF"
    echo ""
    echo "  # 03 - Check for merge conflict markers"
    echo "  cat > .githooks/pre-commit.d/03-no-conflict-markers.sh << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "if git diff --cached | grep -E '^[+].*(<<<<<<|======|>>>>>>)' > /dev/null; then"
    echo "    echo \"Merge conflict markers found!\""
    echo "    exit 1"
    echo "fi"
    echo "HOOKEOF"
    echo ""
    echo "  chmod +x .githooks/pre-commit.d/*"
    echo ""
    echo "  # Step 4: Configure Git to use the hooks directory"
    echo "  git config core.hooksPath .githooks"
    echo ""
    echo "  # Step 5: Test the hook chain"
    echo "  git add . && git commit -m 'chore: add hook infrastructure'"
    echo "  # All three hooks run in order (01, 02, 03)"
    echo ""
    echo "Key takeaway:"
    echo "  An orchestrator pattern keeps hooks modular and maintainable."
    echo "  Each hook is a standalone script in pre-commit.d/. The orchestrator"
    echo "  runs them in sorted order and collects exit codes."
}

# === Exercise 4: Commit Message Enforcement ===
# Problem: Create a commit-msg hook that enforces the Conventional
# Commits format and set up commitlint for a team project.
exercise_4() {
    echo "=== Exercise 4: Commit Message Enforcement ==="
    echo ""
    echo "Solution commands:"
    echo ""
    echo "  # === Option A: Custom shell script ==="
    echo ""
    echo "  # Step 1: Create a commit-msg hook"
    echo "  cat > .githooks/commit-msg << 'HOOKEOF'"
    echo "#!/bin/bash"
    echo "COMMIT_MSG_FILE=\$1"
    echo "FIRST_LINE=\$(head -1 \"\$COMMIT_MSG_FILE\")"
    echo ""
    echo "PATTERN=\"^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)(\\(.+\\))?(!)?: .{1,72}\$\""
    echo ""
    echo "if ! echo \"\$FIRST_LINE\" | grep -qE \"\$PATTERN\"; then"
    echo "    echo \"Invalid commit message format!\""
    echo "    echo \"Expected: <type>(<scope>): <description>\""
    echo "    echo \"Types: feat, fix, docs, style, refactor, perf, test, build, ci, chore, revert\""
    echo "    echo \"Your message: \$FIRST_LINE\""
    echo "    exit 1"
    echo "fi"
    echo "HOOKEOF"
    echo "  chmod +x .githooks/commit-msg"
    echo ""
    echo "  # Step 2: Test with valid and invalid messages"
    echo "  echo 'test' > test.txt && git add test.txt"
    echo "  git commit -m 'bad message'"
    echo "  # REJECTED: Invalid commit message format!"
    echo ""
    echo "  git commit -m 'feat: add test file'"
    echo "  # ACCEPTED: matches the pattern"
    echo ""
    echo "  # === Option B: commitlint (Node.js projects) ==="
    echo ""
    echo "  # Step 3: Install commitlint"
    echo "  npm install --save-dev @commitlint/cli @commitlint/config-conventional"
    echo ""
    echo "  # Step 4: Create commitlint.config.mjs"
