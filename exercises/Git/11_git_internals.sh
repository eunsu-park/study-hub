exercise_5() {
    echo "=== Exercise 5: Pack Files and Garbage Collection ==="
    echo ""
    echo "Solution commands:"
    echo ""
    echo "  # Step 1: Create a repo with several commits"
    echo "  git init pack-lab && cd pack-lab"
    echo "  for i in 1 2 3 4 5; do"
    echo "    echo \"version \$i\" > data.txt"
    echo "    git add data.txt"
    echo "    git commit -m \"Update data to version \$i\""
    echo "  done"
    echo ""
    echo "  # Step 2: Count loose objects"
    echo "  git count-objects -v"
    echo "  # count: N       (loose objects)"
    echo "  # in-pack: 0     (no pack files yet)"
    echo ""
    echo "  # Step 3: Run garbage collection to pack objects"
    echo "  git gc"
    echo "  # Enumerating objects: done."
    echo "  # Counting objects: done."
    echo "  # Compressing objects: done."
    echo ""
    echo "  # Step 4: Check objects again"
    echo "  git count-objects -v"
    echo "  # count: 0       (no more loose objects)"
    echo "  # in-pack: N     (all objects are now packed)"
    echo "  # size-pack: M   (total pack size in KB)"
    echo ""
    echo "  # Step 5: Inspect the pack file"
    echo "  git verify-pack -v .git/objects/pack/pack-*.idx | head -15"
    echo "  # Shows each object with type, size, and delta information"
    echo "  # Objects with a 'depth' column are delta-compressed against a base"
    echo ""
    echo "  # Step 6: Verify repository integrity"
    echo "  git fsck"
    echo "  # Should report no errors"
    echo ""
    echo "Key takeaway:"
    echo "  Loose objects are individual compressed files (one per object)."
    echo "  git gc packs them using delta compression, dramatically reducing"
    echo "  disk usage. Git runs gc automatically when thresholds are reached."
}

